import fs from 'node:fs/promises';
import sharp from 'sharp';
import { crc32 } from 'node:zlib';
import { brandMarkPath, brandColors } from '../src/config/brand.ts';

// Preserve vector provenance in a standard PNG text chunk, including on regeneration.
function provenance(png, origin) {
  const text = Buffer.from('impeccable:prompt\0' + origin, 'utf8');
  const chunk = Buffer.alloc(text.length + 12);
  chunk.writeUInt32BE(text.length, 0);
  chunk.write('tEXt', 4, 'ascii');
  text.copy(chunk, 8);
  chunk.writeUInt32BE(crc32(chunk.subarray(4, -4)), chunk.length - 4);
  return Buffer.concat([png.subarray(0, -12), chunk, png.subarray(-12)]);
}

